#!/usr/bin/env node
/**
 * Generates src/styles/shared.ts (card/input/btn* shared styles) from the
 * Tailwind @apply definitions in src/index.css via the StyleX mapper.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { chunkToStyles } from './tw-to-stylex.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT = resolve(ROOT, 'src/styles/shared.ts');

const CLASS_DEFS = {
  card: 'bg-white border border-slate-200 rounded-xl shadow-sm dark:bg-slate-850 dark:border-slate-700/50',
  input:
    'bg-white border border-slate-300 rounded-lg px-3 py-2 text-sm text-slate-900 placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-indigo-500/50 focus:border-indigo-500 dark:bg-slate-900 dark:border-slate-700 dark:text-slate-100 dark:placeholder:text-slate-500 min-h-11',
  btn: 'inline-flex items-center justify-center rounded-lg px-4 py-2 text-sm font-medium transition-colors min-h-11',
  btnPrimary: 'bg-indigo-600 text-white hover:bg-indigo-500',
  btnSecondary: 'bg-slate-200 text-slate-800 hover:bg-slate-300 dark:bg-slate-700 dark:text-slate-100 dark:hover:bg-slate-600',
  btnGhost: 'text-slate-600 hover:bg-slate-200 hover:text-slate-900 dark:text-slate-300 dark:hover:bg-slate-800 dark:hover:text-white',
};

const knownVars = new Set();
for (const m of readFileSync(resolve(ROOT, 'src/styles/tokens.stylex.ts'), 'utf8').matchAll(/\s'([^']+)':\s'([^']+)',/g)) {
  knownVars.add(m[1]);
}

function serialize(obj, indent = 4) {
  const pad = ' '.repeat(indent);
  const lines = [];
  for (const [k, v] of Object.entries(obj)) {
    if (v && typeof v === 'object' && v.__stylexVar) {
      lines.push(`${pad}${JSON.stringify(k)}: colors[${JSON.stringify(v.__stylexVar)}],`);
    } else if (v && typeof v === 'object') {
      lines.push(`${pad}${JSON.stringify(k)}: {`);
      lines.push(serialize(v, indent + 2).trimEnd());
      lines.push(`${pad}},`);
    } else {
      lines.push(`${pad}${JSON.stringify(k)}: ${JSON.stringify(v)},`);
    }
  }
  return lines.join('\n') + '\n';
}

let body = '';
for (const [key, cls] of Object.entries(CLASS_DEFS)) {
  const obj = chunkToStyles(cls, knownVars);
  if (!obj) throw new Error(`No style for ${key}`);
  body += `  ${key}: {\n${serialize(obj).trimEnd()}\n  },\n`;
}

const file = `/**
 * Shared component styles re-authored from the Tailwind @apply classes that
 * used to live in src/index.css. Components import via
 * \`import { shared } from '../../styles/shared'\`.
 * Generated by scripts/gen-shared-stylex.mjs.
 */
import * as stylex from '@stylexjs/stylex';
import { colors } from './tokens.stylex';

export const shared = stylex.create({
${body}});
`;

writeFileSync(OUT, file);
console.log(`Wrote ${OUT}`);